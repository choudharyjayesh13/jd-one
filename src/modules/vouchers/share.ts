"use client";
/**
 * Voucher → image → WhatsApp. On phones the share sheet opens with the image
 * attached (pick the accounts group). Where the browser cannot share files
 * (most desktops) the image is downloaded and WhatsApp opens with the text.
 */
import type { Row } from "@/core/schema/types";
import { formatDate, formatMoney } from "@/core/format";
import { amountInWords } from "./words";

const W = 1080;
const H = 1440;

function wrap(ctx: CanvasRenderingContext2D, text: string, maxWidth: number): string[] {
  const words = text.split(" ");
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    if (ctx.measureText(test).width > maxWidth && line) {
      lines.push(line);
      line = w;
    } else line = test;
  }
  if (line) lines.push(line);
  return lines;
}

export function voucherTitle(r: Row): string {
  return r.vtype === "RV" ? "Receipt voucher" : "Payment voucher";
}

async function drawVoucher(r: Row, unitName: string): Promise<Blob> {
  if (typeof document !== "undefined" && document.fonts) await document.fonts.ready.catch(() => undefined);
  const canvas = document.createElement("canvas");
  canvas.width = W;
  canvas.height = H;
  const c = canvas.getContext("2d")!;
  const serif = '"Cormorant Garamond", Georgia, serif';
  const sans = '"Jost", -apple-system, "Segoe UI", sans-serif';

  c.fillStyle = "#FBF8F2";
  c.fillRect(0, 0, W, H);
  c.fillStyle = "#B8924A";
  c.fillRect(0, 0, W, 14);

  const x = 90;
  let y = 150;
  c.fillStyle = "#1E1A14";
  c.font = `700 64px ${serif}`;
  c.fillText(unitName.toUpperCase(), x, y);
  y += 50;
  c.fillStyle = "#8A672A";
  c.font = `500 26px ${sans}`;
  c.fillText("JD STAYS & HOSPITALITY · JD GROUP", x, y);
  y += 50;
  c.fillStyle = "#D9CCB4";
  c.fillRect(x, y, W - 2 * x, 2);

  y += 90;
  c.fillStyle = "#1E1A14";
  c.font = `600 58px ${serif}`;
  c.fillText(voucherTitle(r), x, y);
  c.font = `500 30px ${sans}`;
  c.textAlign = "right";
  c.fillText(String(r.voucher_no ?? ""), W - x, y);
  c.textAlign = "left";

  const rows: [string, string][] = [
    ["Date", formatDate(r.date)],
    [r.vtype === "RV" ? "Received from" : "Paid to", String(r.party ?? "—")],
    ["For", String(r.against ?? "—")],
    ["Mode", String(r.mode ?? "—")],
    ["Reference", String(r.reference ?? "—")],
    ["Status", String(r.status ?? "")],
  ];
  y += 60;
  for (const [k, v] of rows) {
    y += 70;
    c.fillStyle = "#5C5244";
    c.font = `400 30px ${sans}`;
    c.fillText(k, x, y);
    c.fillStyle = "#1E1A14";
    c.font = `500 32px ${sans}`;
    c.textAlign = "right";
    const lines = wrap(c, v, 560).slice(0, 2);
    lines.forEach((l, i) => c.fillText(l, W - x, y + i * 40));
    c.textAlign = "left";
    y += (lines.length - 1) * 40;
    c.strokeStyle = "#D9CCB4";
    c.setLineDash([6, 8]);
    c.beginPath();
    c.moveTo(x, y + 26);
    c.lineTo(W - x, y + 26);
    c.stroke();
    c.setLineDash([]);
  }

  y += 130;
  c.fillStyle = "#5C5244";
  c.font = `500 28px ${sans}`;
  c.fillText("AMOUNT", x, y);
  c.fillStyle = "#1E1A14";
  c.font = `700 86px ${serif}`;
  c.textAlign = "right";
  c.fillText(formatMoney(r.amount), W - x, y + 10);
  c.textAlign = "left";
  y += 70;
  c.fillStyle = "#5C5244";
  c.font = `italic 400 28px ${sans}`;
  wrap(c, amountInWords(Number(r.amount) || 0), W - 2 * x).forEach((l, i) => c.fillText(l, x, y + i * 38));

  y = H - 210;
  c.fillStyle = "#F3ECDF";
  c.fillRect(x, y, W - 2 * x, 70);
  c.fillStyle = "#1E1A14";
  c.font = `500 26px ${sans}`;
  c.fillText(`Posted to ledger: ${String(r.ledger ?? "JD Stays & Hospitality")}`, x + 24, y + 45);

  c.fillStyle = "#8C8273";
  c.font = `400 22px ${sans}`;
  c.fillText("Generated by JD One · app.myjdgroup.com", x, H - 70);

  return new Promise((resolve, reject) => canvas.toBlob((b) => (b ? resolve(b) : reject(new Error("Could not make the voucher image"))), "image/png"));
}

export async function shareVoucher(r: Row, unitName: string): Promise<"shared" | "downloaded"> {
  const blob = await drawVoucher(r, unitName);
  const name = `${String(r.voucher_no ?? "voucher").replace(/\//g, "-")}.png`;
  const file = new File([blob], name, { type: "image/png" });
  const text = `${voucherTitle(r)} ${String(r.voucher_no ?? "")} · ${String(r.party ?? "")} · ${formatMoney(r.amount)} · ${String(r.status ?? "")}`;
  const nav = navigator as Navigator & { canShare?: (d: ShareData) => boolean };
  if (nav.share && nav.canShare?.({ files: [file] })) {
    try {
      await nav.share({ files: [file], text, title: String(r.voucher_no ?? "Voucher") });
      return "shared";
    } catch (e) {
      if ((e as Error).name === "AbortError") return "shared";
    }
  }
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
  window.open(`https://wa.me/?text=${encodeURIComponent(text)}`, "_blank", "noopener");
  return "downloaded";
}
